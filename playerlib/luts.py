"""
LUT discovery and application.

Two slots are kept independently so a Color-Space-Transform LUT (e.g. S-Log3
to Rec.709) can stack with a creative Look LUT (e.g. Kodak 2383). Both are
applied via mpv's `lut3d` video filter using tetrahedral interpolation —
preferred over trilinear for log source material because it preserves
saturation in the upper highlights.

Folder layout (relative to project root):
    luts/conversions/   generated by lut_generator.py (Sony S-Log3 -> ...)
    luts/cinematic/     bundled MIT-licensed film emulations (YahiaAngelo)
    luts/user/          empty by default; drop your own .cube files here

A LUT is just `{name: str, path: Path, category: str}`.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

# PyInstaller-aware: in a frozen build, luts/ sits next to the exe.
if getattr(sys, "frozen", False):
    PROJECT_ROOT = Path(sys.executable).resolve().parent
else:
    PROJECT_ROOT = Path(__file__).resolve().parent.parent
LUTS_ROOT = PROJECT_ROOT / "luts"

# Categories the UI cares about; ordering = display order.
CATEGORIES = ("conversions", "cinematic", "user")
LUT_EXTS = (".cube", ".3dl")


@dataclass(frozen=True)
class Lut:
    name: str          # display name
    path: Path         # absolute path on disk
    category: str      # one of CATEGORIES


def _humanize(filename: str) -> str:
    """Turn a stem like 'kodak_portra_400_plus' into 'Kodak Portra 400 Plus'."""
    stem = Path(filename).stem
    # Sony's machine-style names like 'SLog3_SGamut3Cine_to_Rec709' deserve
    # a separate cleanup pass.
    s = stem.replace("_", " ").replace("-", " ").replace("plus", "+")
    # Title-case but keep all-caps tokens (Rec.709, DCI, P3, etc.) intact.
    parts = []
    for word in s.split():
        if word.upper() in ("REC", "DCI", "P3", "BT", "HDR", "SDR", "PQ", "HLG", "OLED"):
            parts.append(word.upper())
        elif word in ("Slog3", "Sgamut3cine"):
            parts.append("S-Log3" if word == "Slog3" else "S-Gamut3.Cine")
        else:
            parts.append(word.title())
    return " ".join(parts).replace("Slog3", "S-Log3")


def discover() -> dict[str, list[Lut]]:
    """Scan luts/ and return categorized lists. Missing folders are tolerated."""
    out: dict[str, list[Lut]] = {c: [] for c in CATEGORIES}
    if not LUTS_ROOT.is_dir():
        return out
    for category in CATEGORIES:
        folder = LUTS_ROOT / category
        if not folder.is_dir():
            continue
        files = sorted(
            (p for p in folder.iterdir()
             if p.is_file() and p.suffix.lower() in LUT_EXTS),
            key=lambda p: p.name.lower(),
        )
        for p in files:
            out[category].append(Lut(name=_humanize(p.name), path=p, category=category))
    return out


def apply_to(player, *, cst: Path | None, look: Path | None) -> None:
    """Apply the active LUT to mpv via the `lut` property (GPU pipeline).
    Single-slot for now: when both CST and Look are set, CST wins. True
    stacking would require composing the two .cube files into one.

    Order of property writes matters: set `lut-type` BEFORE `lut`, otherwise
    mpv loads the LUT under whatever type was previously set and may not
    re-evaluate when the type changes.

    Two slots stack as a vf chain in this order:
       source -> CST -> Look -> display
    The CST takes the source colour space (e.g. S-Log3 / S-Gamut3.Cine) into
    the Look's expected input space (Rec.709 for the bundled film LUTs).
    Without CST first, applying a Rec.709-input creative LUT to S-Log3 pixels
    looks wrong.

    Uses the same per-label remove+append pattern that worked in the
    single-slot version (commit e40cc75) — extended to two slots. Avoids
    `vf set` (atomic replacement) because that variant fails to take visible
    effect on this libmpv build for reasons we couldn't isolate."""
    sys.stderr.write(f"[luts] cst={cst} look={look}\n")

    for path in (cst, look):
        if path is not None and not Path(path).is_file():
            sys.stderr.write(f"[luts] file does NOT exist: {path}\n")
            raise FileNotFoundError(path)

    # Step 1 — remove our previous filters by label. mpv raises if the label
    # isn't present; that's fine on first call. Includes the legacy
    # `@playerlut` from earlier single-slot builds so an old install upgrades
    # cleanly.
    for label in ("@playercst", "@playerlook", "@playerlut"):
        try:
            player.command("vf", "remove", label)
            sys.stderr.write(f"[luts] removed {label}\n")
        except Exception:
            pass

    # Step 2 — clear the legacy `lut` property in case an earlier code path
    # stuck a value there.
    try:
        player["lut"] = ""
    except Exception:
        pass

    # Step 3 — append fresh, one filter per slot. Same exact pattern as the
    # working single-slot version: try `vf append` with a labelled lut3d
    # filter and a single-quoted file path.
    def _append_one(label: str, path: Path) -> None:
        path_str = str(path).replace("\\", "/")
        filter_str = f"{label}:lut3d=file='{path_str}':interp=tetrahedral"
        try:
            player.command("vf", "append", filter_str)
            sys.stderr.write(f"[luts] appended {label}\n")
        except Exception as e:
            sys.stderr.write(f"[luts] append {label} FAILED: {type(e).__name__}: {e}\n")
            raise

    if cst is not None:
        _append_one("@playercst", cst)
    if look is not None:
        _append_one("@playerlook", look)

    # Step 4 — force a re-render so the new filter chain takes effect
    # immediately, even when the player is paused.
    try:
        player.command("seek", "0", "relative-percent", "exact")
    except Exception:
        pass

    sys.stderr.write("[luts] apply complete\n")


def clear(player) -> None:
    apply_to(player, cst=None, look=None)
